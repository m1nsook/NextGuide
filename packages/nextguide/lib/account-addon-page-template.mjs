/**
 * Generated Account Mode public Markdown add-on route.
 *
 * This route NEVER compiles untrusted files as MDX or imports extension code.
 * It renders only verified, explicitly enabled v1 Markdown through NextGuide's
 * safe React Markdown subset, with raw HTML displayed as text.
 */
const TEMPLATE = `// Generated by NextGuide CLI. Edit freely; NextGuide never overwrites these files.
import { cache } from "react"
import { connection } from "next/server"
import { notFound } from "next/navigation"
import { Markdown } from "nextguide/components"
import { createAccountAddonManager } from "nextguide/extensions/site-manager"

const addonId = /^[a-z0-9]+(?:-[a-z0-9]+)*\\.[a-z0-9]+(?:-[a-z0-9]+)*$/
const pageSegment = /^[a-zA-Z0-9_-]+(?:\\.[a-zA-Z0-9_-]+)*$/

const readPage = cache(async (id__ID_TYPE__, rawPage__PAGE_TYPE__) => {
  // Account Mode is intentionally request-time only; no static export or ISR.
  await connection()
  if (!addonId.test(id) || rawPage.length > 180 ||
      (rawPage && rawPage.split("/").some(part => !part || !pageSegment.test(part)))) return null
  const slug = rawPage === "" ? "index" : rawPage
  try {
    const addon = await createAccountAddonManager({ project: process.cwd() }).readEnabled({ id })
    if (!addon || !addon.manifest || !addon.manifest.entrypoints) return null
    const root = String(addon.manifest.entrypoints.content || "")
    const target = root + "/" + slug + ".md"
    const entry = addon.pages.find(item => item.path === target)
    if (!entry) return null
    const title = slug === "index" ? String(addon.manifest.name || id)
      : (slug.split("/").at(-1) ?? slug).replace(/[-_]/g, " ")
    return { title, id, version: addon.version, markdown: entry.markdown }
  } catch {
    // Missing signed freshness, revoked release, corrupt blob, bad config or
    // failed registry requests must never reveal private state publicly.
    return null
  }
})

export async function generateMetadata({ params }__PARAM_TYPE__) {
  const { id, page = [] } = await params
  const selected = await readPage(id, page.join("/"))
  return selected
    ? { title: selected.title + " · Add-ons", robots: { index: false, follow: false } }
    : { title: "Add-on unavailable", robots: { index: false, follow: false } }
}

export default async function InstalledAddonPage({ params }__PARAM_TYPE__) {
  const { id, page = [] } = await params
  const selected = await readPage(id, page.join("/"))
  if (!selected) notFound()
  return (
    <main className="mx-auto w-full max-w-4xl space-y-7 px-5 py-10 sm:px-10">
      <div className="space-y-2 border-b pb-6">
        <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">Reviewed add-on · {selected.id} · v{selected.version}</p>
        <h1 className="text-3xl font-semibold tracking-tight">{selected.title}</h1>
      </div>
      <article className="prose prose-neutral dark:prose-invert max-w-none">
        <Markdown>{selected.markdown}</Markdown>
      </article>
    </main>
  )
}
`

export function accountAddonDocsRouteSource(typed = true) {
  return TEMPLATE
    .replaceAll("__ID_TYPE__", typed ? ": string" : "")
    .replaceAll("__PAGE_TYPE__", typed ? ": string" : "")
    .replaceAll("__PARAM_TYPE__", typed ? ": { params: Promise<{ id: string; page?: string[] }> }" : "")
}
