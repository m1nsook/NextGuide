import { copyFileSync, constants, existsSync, lstatSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'
import { STARTER_CONTENT } from './starter-content.mjs'
import { GENERATED_MDX_COMPONENTS } from './starter-components.mjs'
import { fullLibSource, fullLayoutSource, fullAppPageSource, fullPagesPageSource, fullStyleSource, fullOgImageSource } from './starter-templates.mjs'

const SIGNATURE = 'Generated by NextGuide CLI. Edit freely; NextGuide never overwrites these files.'

export const APPEARANCE_MODES = Object.freeze(['light', 'dark', 'system'])
export const ACCENT_COLORS = Object.freeze(['blue', 'red', 'green', 'purple', 'yellow', 'orange', 'teal', 'pink'])

export function normalizeAppearance(value = {}) {
  const mode = value?.mode ?? 'light'
  const accent = value?.accent ?? 'blue'
  if (!APPEARANCE_MODES.includes(mode)) throw new Error('Invalid appearance mode: ' + mode + '. Use light, dark or system.')
  if (!ACCENT_COLORS.includes(accent)) throw new Error('Invalid accent: ' + accent + '. Use ' + ACCENT_COLORS.join(', ') + '.')
  return { mode, accent }
}

function shellConfig(basePath = '/docs', appearance = normalizeAppearance()) {
  return `${JSON.stringify({ schemaVersion: 1, mode: 'developer', contentDir: 'content/docs', basePath, appearance, site: { name: 'My Documentation', description: 'Documentation built with NextGuide' } }, null, 2)}\n`
}

function pagesAppSource(typescript, stylesImport = '../styles/nextguide.css') {
  const typeImport = typescript ? 'import type { AppProps } from "next/app"\n' : ''
  const props = typescript ? '{ Component, pageProps }: AppProps' : '{ Component, pageProps }'
  return `// ${SIGNATURE}
${typeImport}import "nextguide/styles.css"
import "${stylesImport}"

export default function App(${props}) {
  return <Component {...pageProps} />
}
`
}

const STARTER_FILES = { ...STARTER_CONTENT, 'nextguide.config.json': shellConfig() }

/**
 * Read paths from the project's own tsconfig/jsconfig. Both files support
 * JSON-with-comments; never change the user's configuration to add an alias.
 */
function stripJsonComments(source) {
  let output = ''
  let quoted = false
  let escape = false
  let lineComment = false
  let blockComment = false
  for (let i = 0; i < source.length; i++) {
    const char = source[i]
    const next = source[i + 1]
    if (lineComment) {
      if (char === '\n') { lineComment = false; output += char }
      continue
    }
    if (blockComment) {
      if (char === '*' && next === '/') { blockComment = false; i++ }
      continue
    }
    if (quoted) {
      output += char
      if (escape) escape = false
      else if (char === '\\') escape = true
      else if (char === '"') quoted = false
      continue
    }
    if (char === '"') { quoted = true; output += char; continue }
    if (char === '/' && next === '/') { lineComment = true; i++; continue }
    if (char === '/' && next === '*') { blockComment = true; i++; continue }
    output += char
  }
  return output.replace(/,\s*([}\]])/g, '$1')
}

function projectImportAliases(directory) {
  for (const filename of ['tsconfig.json', 'jsconfig.json']) {
    const configPath = join(directory, filename)
    if (!existsSync(configPath)) continue
    try {
      const config = JSON.parse(stripJsonComments(readFileSync(configPath, 'utf8')))
      const options = config.compilerOptions ?? {}
      const base = resolve(directory, options.baseUrl ?? '.')
      const aliases = []
      for (const [key, targets] of Object.entries(options.paths ?? {})) {
        if (!key.endsWith('/*') || !Array.isArray(targets)) continue
        for (const target of targets) {
          if (typeof target !== 'string' || !target.endsWith('/*')) continue
          aliases.push({ prefix: key.slice(0, -1), directory: resolve(base, target.slice(0, -1)) })
        }
      }
      // Prefer the conventional @/* alias, then the project's first custom alias.
      return aliases.sort((a, b) => Number(b.prefix === '@/') - Number(a.prefix === '@/'))
    } catch {
      // Malformed or unsupported config: use accurate relative imports.
      return []
    }
  }
  return []
}

/**
 * Resolve every generated local import from the actual importing file:
 * docs, CSS, config, and Pages Router _app. Use an existing matching
 * project alias, otherwise compute a portable relative specifier.
 */
function projectImport(directory, aliases, fromFile, targetFile) {
  const target = resolve(directory, targetFile)
  for (const alias of aliases) {
    const suffix = relative(alias.directory, target)
    if (suffix !== '..' && !suffix.startsWith('..' + sep) && !isAbsolute(suffix)) {
      if (!suffix) continue
      return alias.prefix + suffix.split(sep).join('/')
    }
  }
  const location = resolve(directory, fromFile)
  const specifier = relative(dirname(location), target).split(sep).join('/')
  return specifier.startsWith('.') ? specifier : './' + specifier
}

/**
 * next-themes applies the chosen class and color-scheme to document.documentElement
 * before React hydration. For App Router projects, React also hydrates <html>,
 * so the actual root layout must opt out of checking those theme-owned attributes.
 * This is the same one-element safeguard used by apps/web/app/layout.tsx.
 *
 * Only patch a single, recognizable root <html> opening tag. Never overwrite
 * custom layouts or rewrite user code that does not match this safe pattern.
 */
export function planRootLayoutHydrationPatch(directory, router) {
  if (router.name !== 'App Router') return null
  const candidates = ['tsx', 'jsx', 'js', 'ts']
    .map((ext) => router.folder + '/layout.' + ext)
    .filter((path) => existsSync(join(directory, path)))
  if (candidates.length > 1) {
    throw new Error('Multiple root App Router layouts found: ' + candidates.join(', '))
  }
  if (!candidates.length) return null
  const path = candidates[0]
  const absolute = join(directory, path)
  if (lstatSync(absolute).isSymbolicLink()) {
    throw new Error('Refusing to modify a symbolic-link root layout: ' + path)
  }
  const original = readFileSync(absolute, 'utf8')
  const matches = [...original.matchAll(/<html(?=[\s/>])/g)]
  if (matches.length !== 1) {
    throw new Error('Cannot safely locate the root <html> in ' + path +
      '. Add suppressHydrationWarning to that element for NextGuide themes.')
  }
  const position = matches[0].index
  const end = original.indexOf('>', position)
  if (end < 0) throw new Error('Unclosed root <html> element in ' + path)
  if (/\bsuppressHydrationWarning\b/.test(original.slice(position, end + 1))) return null
  const updated = original.slice(0, position) + '<html suppressHydrationWarning' + original.slice(position + 5)
  return { path, original, updated, backup: path + '.nextguide-backup' }
}

export function planDeveloperProject(directory, inspection, routerOption, options = {}) {
  const basePath = options.basePath ?? '/docs'
  const appearance = normalizeAppearance(options.appearance)
  if (basePath !== '/docs' && basePath !== '/') throw new Error('Documentation path must be /docs or /')
  const available = inspection.routers.filter((router) => !routerOption || (routerOption === 'app' ? router.name === 'App Router' : router.name === 'Pages Router'))
  if (!inspection.ok) throw new Error(inspection.issues.join(' '))
  if (available.length !== 1) {
    throw new Error(available.length ? 'Multiple matching router directories detected. Keep only one or specify an unambiguous project layout.' : 'Requested Next.js router not found. Check --router app|pages.')
  }
  const router = available[0]
  const src = router.folder.startsWith('src/')
  const typed = existsSync(join(directory, 'tsconfig.json'))
  const ext = typed ? 'tsx' : 'jsx'
  const lib = typed ? 'ts' : 'js'
  const root = src ? 'src/' : ''
  const files = { ...STARTER_FILES }
  files['nextguide.config.json'] = shellConfig(basePath, appearance)
  const gettingStartedHref = (basePath === '/' ? '' : basePath) + '/getting-started'
  files['content/docs/index.mdx'] = files['content/docs/index.mdx']
    .replace('[Open the getting started page](/docs/getting-started)', '[Open the getting started page](' + gettingStartedHref + ')')
  if (basePath === '/') {
    for (const filename of Object.keys(files)) {
      if (!filename.startsWith('content/docs/') || !filename.endsWith('.mdx')) continue
      files[filename] = files[filename].replaceAll('href="/docs/', 'href="/').replaceAll('](/docs/', '](/')
    }
  }
  let homeBackup = null
  if (basePath === '/') {
    const existingHome = ['tsx', 'jsx', 'js', 'ts']
      .map((suffix) => router.folder + '/' + (router.name === 'App Router' ? 'page.' : 'index.') + suffix)
      .filter((name) => existsSync(join(directory, name)))
    if (existingHome.length > 1) throw new Error('Multiple home page files found: ' + existingHome.join(', '))
    if (existingHome.length) {
      const existing = existingHome[0]
      const backup = existing + '.nextguide-backup'
      if (!options.replaceHome) throw new Error('The existing homepage at ' + existing +
        ' conflicts with documentation at /. Choose --base-path /docs or confirm the backup with --replace-home.')
      if (existsSync(join(directory, backup))) throw new Error('Cannot back up homepage because ' + backup + ' already exists.')
      homeBackup = { original: existing, backup }
    }
  }
  const aliases = projectImportAliases(directory)
  const libFile = root + 'lib/nextguide.' + lib
  const stylesFile = root + 'styles/nextguide.css'
  const mdxFile = root + 'lib/nextguide-mdx-components.' + ext
  files[mdxFile] = GENERATED_MDX_COMPONENTS
  files[libFile] = fullLibSource(
    projectImport(directory, aliases, libFile, 'nextguide.config.json'),
    projectImport(directory, aliases, libFile, mdxFile.replace(/\.(tsx|jsx)$/, '')),
    basePath, typed
  )
  files[stylesFile] = fullStyleSource(root)
  let patch = null
  if (router.name === 'App Router') {
    patch = planRootLayoutHydrationPatch(directory, router)
    const docsFolder = router.folder + (basePath === '/' ? '/(nextguide)' : '/docs')
    const layoutFile = docsFolder + '/layout.' + ext
    const pageFile = docsFolder + '/[[...slug]]/page.' + ext
    files[layoutFile] = fullLayoutSource(
      typed, basePath,
      projectImport(directory, aliases, layoutFile, libFile.replace(/\.(ts|js)$/, '')),
      projectImport(directory, aliases, layoutFile, stylesFile)
    )
    files[pageFile] = fullAppPageSource(
      typed, basePath, projectImport(directory, aliases, pageFile, libFile.replace(/\.(ts|js)$/, ''))
    )
    // Statically generate one branded social preview for every MDX route.
    const ogFile = docsFolder + '/[[...slug]]/opengraph-image.' + ext
    files[ogFile] = fullOgImageSource(
      typed, projectImport(directory, aliases, ogFile, libFile.replace(/\.(ts|js)$/, ''))
    )
  } else {
    const pageFile = router.folder + (basePath === '/' ? '/[[...slug]].' : '/docs/[[...slug]].') + ext
    files[pageFile] = fullPagesPageSource(
      typed, basePath, projectImport(directory, aliases, pageFile, libFile.replace(/\.(ts|js)$/, '')),
      projectImport(directory, aliases, pageFile, mdxFile.replace(/\.(tsx|jsx)$/, ''))
    )
    const appVariants = ['tsx', 'ts', 'jsx', 'js'].filter((suffix) => existsSync(join(directory, router.folder, '_app.' + suffix)))
    if (appVariants.length > 1) throw new Error('Multiple pages/_app entrypoints detected; please use a single file.')
    const appFile = router.folder + '/_app.' + (appVariants[0] ?? ext)
    const cssImport = projectImport(directory, aliases, appFile, stylesFile)
    if (appVariants.length === 0) files[appFile] = pagesAppSource(typed, cssImport)
    else {
      const original = readFileSync(join(directory, appFile), 'utf8')
      const needed = ['import "nextguide/styles.css"', 'import "' + cssImport + '"']
        .filter((line) => !original.includes(line.split('"')[1]))
      if (needed.length) patch = { path: appFile, original, updated: needed.join('\n') + '\n' + original, backup: appFile + '.nextguide-backup' }
    }
  }
  return { directory, router, typed, files, patch, basePath, appearance, homeBackup }
}

export function applyPlan(plan, dryRun = false) {
  const conflicts = Object.keys(plan.files).filter((file) => existsSync(join(plan.directory, file)))
  if (conflicts.length) throw new Error('Refusing to overwrite existing project files:\\n' + conflicts.map((x) => '  ' + x).join('\\n'))
  const patch = plan.patch
  if (patch && existsSync(join(plan.directory, patch.backup))) {
    throw new Error('Cannot back up ' + patch.path + ': ' + patch.backup + ' already exists.')
  }
  const backedUp = [
    ...(plan.homeBackup ? [plan.homeBackup.backup] : []),
    ...(patch ? [patch.backup] : []),
  ]
  if (dryRun) return { created: Object.keys(plan.files), modified: patch ? [patch.path] : [], backedUp }

  const created = []
  let homeMoved = false
  let patchSaved = false
  try {
    if (plan.homeBackup) {
      renameSync(join(plan.directory, plan.homeBackup.original), join(plan.directory, plan.homeBackup.backup))
      homeMoved = true
    }
    for (const [file, content] of Object.entries(plan.files)) {
      const dest = join(plan.directory, file)
      mkdirSync(dirname(dest), { recursive: true })
      writeFileSync(dest, content, { encoding: 'utf8', flag: 'wx' })
      created.push(file)
    }
    if (patch) {
      const dest = join(plan.directory, patch.path)
      if (readFileSync(dest, 'utf8') !== patch.original) {
        throw new Error('Root project file changed while initializing: ' + patch.path)
      }
      copyFileSync(dest, join(plan.directory, patch.backup), constants.COPYFILE_EXCL)
      patchSaved = true
      writeFileSync(dest, patch.updated, 'utf8')
    }
  } catch (error) {
    if (patchSaved) {
      try { copyFileSync(join(plan.directory, patch.backup), join(plan.directory, patch.path)) }
      catch { /* keep the backup for recovery */ }
    }
    for (const file of created.reverse()) {
      try { rmSync(join(plan.directory, file), { force: true }) }
      catch { /* keep original error */ }
    }
    if (homeMoved && plan.homeBackup) {
      try { renameSync(join(plan.directory, plan.homeBackup.backup), join(plan.directory, plan.homeBackup.original)) }
      catch { /* keep the backup for recovery */ }
    }
    throw error
  }
  return { created: Object.keys(plan.files), modified: patch ? [patch.path] : [], backedUp }
}

export function initDeveloper(projectDirectory, inspection, options = {}) {
  const directory = resolve(projectDirectory)
  const plan = planDeveloperProject(directory, inspection, options.router, options)
  const result = applyPlan(plan, options.dryRun)
  return { ...result, router: plan.router, basePath: plan.basePath, appearance: plan.appearance, mode: 'developer', dryRun: !!options.dryRun, projectDirectory: directory }
}