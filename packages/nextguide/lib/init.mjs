export const APPEARANCE_MODES = Object.freeze(['light', 'dark', 'system'])
export const ACCENT_COLORS = Object.freeze(['blue', 'red', 'green', 'purple', 'yellow', 'orange', 'teal', 'pink'])

export function normalizeAppearance(value = {}) {
  const mode = value?.mode ?? 'light'
  const accent = value?.accent ?? 'blue'
  if (!APPEARANCE_MODES.includes(mode)) throw new Error('Invalid appearance mode: ' + mode + '. Use light, dark or system.')
  if (!ACCENT_COLORS.includes(accent)) throw new Error('Invalid accent: ' + accent + '. Use ' + ACCENT_COLORS.join(', ') + '.')
  return { mode, accent }
}

