import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, constants, lstatSync, openSync, closeSync, renameSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { normalizeAppearance, planDeveloperProject, planRootLayoutHydrationPatch } from './init.mjs'

const GENERATED_MARKER = 'Generated by NextGuide CLI.'
const CONFIG_NAME = 'nextguide.config.json'

/** Never follow symlinks while upgrading source files inside an existing project. */
function assertLocalFile(directory, path) {
  const root = resolve(directory)
  const target = resolve(root, path)
  const suffix = relative(root, target)
  if (!suffix || suffix === '..' || suffix.startsWith('..' + sep)) {
    throw new Error('Refusing to access file outside project: ' + path)
  }
  let current = root
  for (const piece of suffix.split(sep)) {
    current = join(current, piece)
    try {
      if (lstatSync(current).isSymbolicLink()) throw new Error('Refusing symbolic link in upgrade path: ' + path)
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error
    }
  }
}

function readConfig(directory) {
  const filename = join(directory, CONFIG_NAME)
  assertLocalFile(directory, CONFIG_NAME)
  if (!existsSync(filename)) throw new Error('NextGuide is not initialized here. Run nextguide init --developer first.')
  let config
  try {
    config = JSON.parse(readFileSync(filename, 'utf8'))
  } catch {
    throw new Error('nextguide.config.json is not valid JSON; fix it before upgrading.')
  }
  if (!config || typeof config !== 'object' || Array.isArray(config)) {
    throw new Error('nextguide.config.json must contain a JSON object.')
  }
  if (config.mode !== 'developer') throw new Error('Only Developer Mode can be upgraded at present.')
  if (typeof config.schemaVersion !== 'number' || config.schemaVersion !== 1) {
    throw new Error('Unsupported NextGuide configuration schema version: ' + String(config.schemaVersion))
  }
  if (config.basePath !== undefined && !['/', '/docs'].includes(config.basePath)) {
    throw new Error('Unsupported basePath in nextguide.config.json: ' + String(config.basePath))
  }
  return config
}

function reserveBackup(directory, path, reserved) {
  for (let number = 0; number < 100; number++) {
    const candidate = path + '.nextguide-backup' + (number ? '.' + number : '')
    assertLocalFile(directory, candidate)
    if (!existsSync(join(directory, candidate)) && !reserved.has(candidate)) {
      reserved.add(candidate)
      return candidate
    }
  }
  throw new Error('Too many backups for ' + path + '. Clean up old backups first.')
}

export function planUpgrade(projectDirectory, inspection, options = {}) {
  const directory = resolve(projectDirectory)
  if (!inspection.ok) throw new Error(inspection.issues.join(' '))
  const current = readConfig(directory)
  const requested = options.appearance ?? {}
  const appearance = normalizeAppearance({
    ...current.appearance,
    ...requested,
  })
  const updated = {
    ...current,
    basePath: current.basePath ?? '/docs',
    appearance: { ...current.appearance, ...appearance },
  }
  const updates = []
  const configFile = join(directory, CONFIG_NAME)
  const oldConfig = readFileSync(configFile, 'utf8')
  const newConfig = JSON.stringify(updated, null, 2) + '\n'
  if (oldConfig !== newConfig) {
    updates.push({ path: CONFIG_NAME, content: newConfig, type: 'config' })
  }

  // Existing alpha installations were generated without this root-layout fix.
  // Repair only the <html> tag in the host project, with a numbered backup.
  // It also works without --refresh-generated, leaving authored MDX untouched.
  const matchingRouters = inspection.routers.filter((router) =>
    !options.router || (options.router === 'app' ? router.name === 'App Router' : router.name === 'Pages Router'))
  if (matchingRouters.length === 1 && matchingRouters[0].name === 'App Router') {
    for (const ext of ['tsx', 'jsx', 'js', 'ts']) {
      const rootLayout = matchingRouters[0].folder + '/layout.' + ext
      if (existsSync(join(directory, rootLayout))) assertLocalFile(directory, rootLayout)
    }
    const patch = planRootLayoutHydrationPatch(directory, matchingRouters[0])
    if (patch) {
      assertLocalFile(directory, patch.path)
      updates.push({ path: patch.path, content: patch.updated, type: 'root-theme' })
    }
  }

  if (options.refreshGenerated) {
    const templates = planDeveloperProject(directory, inspection, options.router, {
      basePath: updated.basePath,
      appearance,
      ngCopyright: updated.ngCopyright,
    })
    for (const [path, content] of Object.entries(templates.files)) {
      // MDX content and _meta.json are always user-owned, even with --refresh-generated.
      if (path === CONFIG_NAME || path.startsWith('content/')) continue
      const destination = join(directory, path)
      assertLocalFile(directory, path)
      if (existsSync(destination)) {
        const existing = readFileSync(destination, 'utf8')
        if (!existing.includes(GENERATED_MARKER)) {
          throw new Error('Refusing to replace user-owned file: ' + path)
        }
        if (existing === content) continue
        updates.push({ path, content, type: 'generated' })
      } else {
        updates.push({ path, content, type: 'new' })
      }
    }
  }
  const reserved = new Set()
  for (const update of updates) {
    if (update.type !== 'new') update.backup = reserveBackup(directory, update.path, reserved)
  }
  return {
    projectDirectory: directory,
    basePath: updated.basePath,
    appearance,
    updates,
    refreshGenerated: !!options.refreshGenerated,
  }
}

export function applyUpgrade(plan, dryRun = false) {
  const changes = plan.updates.map(({ path, type, backup }) => ({ path, type, backup: backup ?? null }))
  if (dryRun || !changes.length) return { ...plan, dryRun, changes }
  const applied = []
  try {
    for (const update of plan.updates) {
      assertLocalFile(plan.projectDirectory, update.path)
      if (update.backup) assertLocalFile(plan.projectDirectory, update.backup)
      const destination = join(plan.projectDirectory, update.path)
      mkdirSync(dirname(destination), { recursive: true })
      if (update.type === 'new') {
        // The exclusive open distinguishes an existing user file from a partially
        // created file that we own. Only the latter may be removed on rollback.
        const fd = openSync(destination, 'wx')
        applied.push(update)
        try {
          writeFileSync(fd, update.content, 'utf8')
        } finally {
          closeSync(fd)
        }
        continue
      }
      if (update.backup) {
        copyFileSync(destination, join(plan.projectDirectory, update.backup), constants.COPYFILE_EXCL)
      }
      // Write a complete replacement beside the original before swapping it.
      // Failure during writing leaves the original untouched and its backup intact.
      const temp = destination + '.nextguide-tmp-' + randomUUID()
      try {
        writeFileSync(temp, update.content, { encoding: 'utf8', flag: 'wx' })
        renameSync(temp, destination)
        applied.push(update)
      } finally {
        rmSync(temp, { force: true })
      }
    }
  } catch (error) {
    for (const update of applied.reverse()) {
      const dest = join(plan.projectDirectory, update.path)
      try {
        if (update.backup) copyFileSync(join(plan.projectDirectory, update.backup), dest)
        else rmSync(dest, { force: true })
      } catch { /* Backups are retained for manual recovery. */ }
    }
    throw error
  }
  return { ...plan, dryRun: false, changes }
}

export function upgradeDeveloper(projectDirectory, inspection, options = {}) {
  return applyUpgrade(planUpgrade(projectDirectory, inspection, options), !!options.dryRun)
}
