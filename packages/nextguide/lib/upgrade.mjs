import { existsSync, lstatSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs"
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path"
import { planDeveloperProject } from "./init.mjs"
import { MANIFEST_FILE, hashContent, managedManifest, stringifyManifest } from "./managed.mjs"

function safeTarget(root, name) {
  if (typeof name !== "string" || name.includes("\0") || name.includes("\\") || isAbsolute(name)) {
    throw new Error("Unsafe managed filename: " + name)
  }
  const full = resolve(root, name)
  const rel = relative(root, full)
  if (!rel || rel === ".." || rel.startsWith(".." + sep) || isAbsolute(rel)) {
    throw new Error("Managed file must remain inside the project: " + name)
  }
  let part = root
  for (const segment of rel.split(sep)) {
    part = join(part, segment)
    if (!existsSync(part)) continue
    if (lstatSync(part).isSymbolicLink()) {
      throw new Error("Refusing to upgrade through a symbolic link: " + name)
    }
  }
  return full
}

function readConfig(root) {
  const filename = safeTarget(root, "nextguide.config.json")
  if (!existsSync(filename)) throw new Error("No NextGuide project config found. Run nextguide init first.")
  let value
  try { value = JSON.parse(readFileSync(filename, "utf8")) }
  catch { throw new Error("nextguide.config.json is not valid JSON") }
  if (value?.mode !== "developer") throw new Error("Upgrade currently supports only Developer Mode")
  return value
}

function readPrevious(root) {
  const file = safeTarget(root, MANIFEST_FILE)
  if (!existsSync(file)) return null
  let value
  try { value = JSON.parse(readFileSync(file, "utf8")) }
  catch { throw new Error("NextGuide managed-file manifest is invalid JSON") }
  if (value?.schemaVersion !== 1 || !value.files || typeof value.files !== "object" ||
      Array.isArray(value.files)) {
    throw new Error("Unsupported NextGuide managed-file manifest schema")
  }
  return value
}

function isUserContent(filename) {
  return filename === "nextguide.config.json" || filename.startsWith("content/")
}

function looksLikeLegacyGenerated(filename, content) {
  if (isUserContent(filename)) return false
  if (content.includes("Generated by NextGuide CLI")) return true
  return /(^|\/)styles\/nextguide\.css$/.test(filename) &&
    (content.includes(".ng-starter") || content.includes("NextGuide Developer Mode"))
}

export function planUpgrade(projectDirectory, inspection, options = {}) {
  const directory = resolve(projectDirectory)
  const config = readConfig(directory)
  const previous = readPrevious(directory)
  const projectPlan = planDeveloperProject(directory, inspection, options.router, {
    basePath: config.basePath ?? "/docs",
    appearance: config.appearance ?? { defaultTheme: "system", accent: "blue" },
    replaceHome: false,
  })
  const oldHashes = previous?.files ?? {}
  const changes = []
  const skipped = []
  const nextHashes = { ...oldHashes }
  const desired = Object.entries(projectPlan.files).filter(([name]) => name !== MANIFEST_FILE)

  for (const [name, content] of desired) {
    const full = safeTarget(directory, name)
    if (!existsSync(full)) {
      changes.push({ kind: "create", name, content })
      nextHashes[name] = hashContent(content)
      continue
    }
    if (!lstatSync(full).isFile()) throw new Error("Cannot upgrade non-file path: " + name)
    const current = readFileSync(full, "utf8")
    const currentHash = hashContent(current)
    const updatedHash = hashContent(content)
    if (currentHash === updatedHash) {
      nextHashes[name] = updatedHash
      continue
    }
    if (typeof oldHashes[name] === "string" && /^[a-f0-9]{64}$/.test(oldHashes[name]) &&
        currentHash === oldHashes[name]) {
      changes.push({ kind: "update", name, content })
      nextHashes[name] = updatedHash
      continue
    }
    if (!previous && options.adoptLegacy && looksLikeLegacyGenerated(name, current)) {
      const backup = name + ".nextguide-backup"
      const backupPath = safeTarget(directory, backup)
      if (existsSync(backupPath)) {
        skipped.push({ name, reason: "Backup already exists: " + backup })
        continue
      }
      changes.push({ kind: "backup-and-update", name, backup, content })
      nextHashes[name] = updatedHash
      continue
    }
    skipped.push({ name, reason: isUserContent(name)
      ? "User content/configuration preserved"
      : previous ? "User-modified or unmanaged file preserved" : "Legacy file preserved (use --adopt-legacy with backups)" })
  }
  const record = managedManifest({
    router: projectPlan.router,
    basePath: projectPlan.basePath,
    files: {},
  }, { files: nextHashes })
  const needsManifest = !previous || stringifyManifest(record) !== stringifyManifest(previous)
  if (needsManifest) {
    changes.push({ kind: previous ? "update" : "create", name: MANIFEST_FILE, content: stringifyManifest(record) })
  }
  return { directory, changes, skipped, legacy: !previous,
    basePath: projectPlan.basePath, router: projectPlan.router, dryRun: !!options.dryRun }
}

export function upgradeDeveloper(projectDirectory, inspection, options = {}) {
  const plan = planUpgrade(projectDirectory, inspection, options)
  if (options.dryRun) return { ...plan, dryRun: true }
  // Preflight backup paths, symlinks, and all destination parents before writes.
  for (const op of plan.changes) {
    safeTarget(plan.directory, op.name)
    if (op.backup) safeTarget(plan.directory, op.backup)
  }
  for (const op of plan.changes) {
    const path = safeTarget(plan.directory, op.name)
    mkdirSync(dirname(path), { recursive: true })
    if (op.kind === "backup-and-update") {
      renameSync(path, safeTarget(plan.directory, op.backup))
      writeFileSync(path, op.content, { encoding: "utf8", flag: "wx" })
    } else if (op.kind === "create") {
      writeFileSync(path, op.content, { encoding: "utf8", flag: "wx" })
    } else {
      writeFileSync(path, op.content, "utf8")
    }
  }
  return { ...plan, dryRun: false }
}
