const API = `// Generated by NextGuide CLI. Edit freely; NextGuide never overwrites these files.
import { ACCOUNT_COOKIE, AccountError, accountStatus, beginEnrollment, finishEnrollment, beginAuthenticatorRotation, finishAuthenticatorRotation, renewRecoveryCodes, revokeAllSessions, sameOrigin, signIn, signOut } from "nextguide/account/server"

export const runtime = "nodejs"

function respond(payload__OBJECT_TYPE__, status = 200, extra__HEADERS_TYPE__ = {}) {
  return Response.json(payload, { status, headers: { "Cache-Control": "no-store", ...extra } })
}
function cookieFrom(request__REQUEST_TYPE__) {
  const match = (request.headers.get("cookie") || "").match(/(?:^|;\\s*)ng_account_session=([^;]+)/)
  return match ? decodeURIComponent(match[1]) : undefined
}
function authCookie(token__TOKEN_TYPE__, request__REQUEST_TYPE__) {
  const secure = new URL(process.env.NEXTGUIDE_PUBLIC_URL || request.url).protocol === "https:"
  return ACCOUNT_COOKIE + "=" + (token ? encodeURIComponent(token) : "") +
    "; Path=/; HttpOnly; SameSite=Strict; Max-Age=" + (token ? "43200" : "0") +
    (secure ? "; Secure" : "")
}
async function jsonBody(request__REQUEST_TYPE__) {
  if (!(request.headers.get("content-type") || "").toLowerCase().startsWith("application/json")) {
    throw new AccountError("JSON content type required.", 415)
  }
  const reader = request.body?.getReader()
  if (!reader) throw new AccountError("Request body required.", 400)
  const chunks = []
  let size = 0
  while (true) {
    const next = await reader.read()
    if (next.done) break
    size += next.value.byteLength
    if (size > 4096) { await reader.cancel(); throw new AccountError("Request is too large.", 413) }
    chunks.push(Buffer.from(next.value))
  }
  try {
    const value = JSON.parse(Buffer.concat(chunks).toString("utf8"))
    if (!value || typeof value !== "object" || Array.isArray(value)) throw Error("not an object")
    return value
  } catch { throw new AccountError("Invalid JSON request.", 400) }
}
function handleError(error__ERROR_TYPE__) {
  if (error instanceof AccountError) {
    return respond({ error: error.message }, error.status, error.retryAfter ? { "Retry-After": String(error.retryAfter) } : {})
  }
  // Do not reveal account storage paths, secrets or stack traces to the browser.
  console.error("[nextguide/account] Account API failed:", error instanceof Error ? error.name : "Unknown error")
  return respond({ error: "Account service unavailable." }, 503)
}

export async function GET(request__REQUEST_TYPE__, { params }__PARAM_TYPE__) {
  if ((await params).action !== "status") return respond({ error: "Not found" }, 404)
  try { return respond(accountStatus(process.cwd(), cookieFrom(request))) }
  catch (error) { return handleError(error) }
}

export async function POST(request__REQUEST_TYPE__, { params }__PARAM_TYPE__) {
  const action = (await params).action
  if (!["begin", "finish", "login", "logout", "rotate-begin", "rotate-finish", "recovery-renew", "logout-all"].includes(action)) return respond({ error: "Not found" }, 404)
  if (!sameOrigin(request)) return respond({ error: "Invalid request origin." }, 403)
  try {
    if (action === "logout") {
      signOut(process.cwd(), cookieFrom(request))
      return new Response(null, { status: 303, headers: { "Location": "/login", "Set-Cookie": authCookie(null, request), "Cache-Control": "no-store" } })
    }
    const data = await jsonBody(request)
    if (["rotate-begin", "rotate-finish", "recovery-renew", "logout-all"].includes(action)) {
      const session = cookieFrom(request)
      if (!session) return respond({ error: "Sign in first." }, 401)
      if (action === "rotate-begin") return respond(await beginAuthenticatorRotation(process.cwd(), session, data.code))
      if (action === "rotate-finish") {
        const updated = finishAuthenticatorRotation(process.cwd(), session, data.code)
        return respond({ recoveryCodes: updated.recoveryCodes }, 200, { "Set-Cookie": authCookie(updated.session, request) })
      }
      if (action === "recovery-renew") return respond(renewRecoveryCodes(process.cwd(), session, data.code))
      revokeAllSessions(process.cwd(), session)
      return respond({ ok: true }, 200, { "Set-Cookie": authCookie(null, request) })
    }
    if (action === "begin") {
      const result = await beginEnrollment(process.cwd(), data.token)
      return respond(result)
    }
    if (action === "finish") {
      const result = finishEnrollment(process.cwd(), data.token, data.code)
      return respond({ recoveryCodes: result.recoveryCodes }, 200, { "Set-Cookie": authCookie(result.session, request) })
    }
    const result = signIn(process.cwd(), data.code)
    return respond({ ok: true, usedRecovery: result.usedRecovery }, 200, { "Set-Cookie": authCookie(result.session, request) })
  } catch (error) { return handleError(error) }
}
`

function render(template, replacements) {
  return Object.entries(replacements).reduce((result, [key, value]) => result.replaceAll(key, value), template)
}

export function accountStarterFiles(folder, typed, docsPath) {
  const ext = typed ? "tsx" : "jsx"
  const routeExt = typed ? "ts" : "js"
  const page = mode => render(PAGE, { "__MODE__": mode })
  const media = render(MEDIA_ROUTE, {
    "__REQUEST_TYPE__": typed ? ": Request" : "",
    "__MEDIA_PARAM_TYPE__": typed ? ": { params: Promise<{ name: string }> }" : "",
  })
  const api = render(API, {
    "__REQUEST_TYPE__": typed ? ": Request" : "",
    "__PARAM_TYPE__": typed ? ": { params: Promise<{ action: string }> }" : "",
    "__OBJECT_TYPE__": typed ? ": unknown" : "",
    "__HEADERS_TYPE__": typed ? ": Record<string, string>" : "",
    "__TOKEN_TYPE__": typed ? ": string | null" : "",
    "__ERROR_TYPE__": typed ? ": unknown" : "",
  })
  return {
    [folder + "/setup/page." + ext]: page("setup"),
    [folder + "/login/page." + ext]: page("login"),
    [folder + "/admin/page." + ext]: render(ADMIN, { "__DOCS_PATH__": docsPath }),
    [folder + "/api/nextguide/account/[action]/route." + routeExt]: api,
    [folder + "/api/nextguide/studio/[action]/route." + routeExt]: fullStudioRouteSource(typed),
    [folder + "/nextguide/media/[name]/route." + routeExt]: media,
  }
}

function staticExport(directory) {
  for (const name of ["next.config.mjs", "next.config.js", "next.config.cjs", "next.config.ts"]) {
    const path = join(directory, name)
    if (!existsSync(path)) continue
    if (/\boutput\s*:\s*["']export["']/.test(readFileSync(path, "utf8"))) return true
  }
  return false
}

export function initAccount(projectDirectory, inspection, options = {}) {
  const directory = resolve(projectDirectory)
  if (options.router && options.router !== "app") {
    throw new Error("Account Mode currently requires Next.js App Router. Use --router app.")
  }
  if (!inspection?.routers?.some(router => router.name === "App Router")) {
    throw new Error("Account Mode requires a Next.js App Router project.")
  }
  if (staticExport(directory)) {
    throw new Error("Account Mode needs a running Next.js server. Remove output: 'export' from next.config and use Developer Mode for GitHub Pages.")
  }
  const plan = planDeveloperProject(directory, inspection, "app", options)
  const config = JSON.parse(plan.files["nextguide.config.json"])
  config.mode = "account"
  plan.files["nextguide.config.json"] = JSON.stringify(config, null, 2) + "\n"
  const extra = accountStarterFiles(plan.router.folder, plan.typed, plan.basePath)
  Object.assign(plan.files, extra)
  // Account Mode must never statically cache its sidebar, page index, site title
  // or theme: edits made in /admin should appear on the next request, without
  // rebuilding the entire Next.js server.
  const ext = plan.typed ? "tsx" : "jsx"
  const layoutFile = plan.router.folder + (plan.basePath === "/" ? "/(nextguide)" : "/docs") + "/layout." + ext
  let layout = plan.files[layoutFile]
  if (!layout || !layout.includes("const [navigation, searchIndex] = await Promise.all([getSidebar(), getSearchIndex()])")) {
    throw new Error("NextGuide account layout is incompatible with the generated starter.")
  }
  layout = layout.replace('import { Suspense } from "react"', 'import { Suspense } from "react"\nimport { connection } from "next/server"\nimport { getStudioSettings } from "nextguide/account/cms"')
  layout = layout.replace(
    "  const [navigation, searchIndex] = await Promise.all([getSidebar(), getSearchIndex()])",
    "  await connection()\n  const settings = getStudioSettings(process.cwd())\n  const [navigation, searchIndex] = await Promise.all([getSidebar(), getSearchIndex()])"
  )
  layout = layout.replace('defaultTheme={appearance.mode as "light" | "dark" | "system"}', "defaultTheme={settings.theme}")
    .replace("defaultTheme={appearance.mode}", "defaultTheme={settings.theme}")
    .replace("data-ng-accent={appearance.accent}", "data-ng-accent={settings.accent}")
    .replace("siteName={site.name}", "siteName={settings.name}")
    .replace('siteLogo={branding.logo}', "siteLogo={settings.logo}")
    .replace("footerEnabled={ngCopyright.enabled !== false}", "footerEnabled={settings.copyrightEnabled}")
    .replace("footerText={ngCopyright.text}", "footerText={settings.copyrightText}")
    .replace("footerHref={ngCopyright.href}", "footerHref={settings.copyrightHref}")
  // The account wizard's font selectors must change the actual published docs,
  // not merely show sample labels in the dashboard.
  layout = layout.replace(
    'import { Inter, JetBrains_Mono } from "next/font/google"',
    'import { Inter, JetBrains_Mono, Geist, Geist_Mono, IBM_Plex_Sans, IBM_Plex_Mono } from "next/font/google"'
  )
  layout = layout.replace(
    'const fontMono = JetBrains_Mono({ subsets: ["latin"], variable: "--font-mono" })',
    'const fontMono = JetBrains_Mono({ subsets: ["latin"], variable: "--font-mono" })\n' +
    'const fontGeist = Geist({ subsets: ["latin"], variable: "--ng-geist" })\n' +
    'const fontGeistMono = Geist_Mono({ subsets: ["latin"], variable: "--ng-geist-mono" })\n' +
    'const fontIbm = IBM_Plex_Sans({ subsets: ["latin"], weight: ["400", "500", "600", "700"], variable: "--ng-ibm-plex" })\n' +
    'const fontIbmMono = IBM_Plex_Mono({ subsets: ["latin"], weight: ["400", "500", "600", "700"], variable: "--ng-ibm-plex-mono" })\n' +
    'const fontClasses = [fontSans.variable, fontMono.variable, fontGeist.variable, fontGeistMono.variable, fontIbm.variable, fontIbmMono.variable].join(" ")'
  )
  layout = layout.replace(
    '  const settings = getStudioSettings(process.cwd())',
    '  const settings = getStudioSettings(process.cwd())\n' +
    '  const sansFonts = { inter: fontSans.style.fontFamily, geist: fontGeist.style.fontFamily, "ibm-plex-sans": fontIbm.style.fontFamily, "segoe-ui": "\\"Segoe UI\\", system-ui, sans-serif", system: "system-ui, sans-serif" }\n' +
    '  const codeFonts = { "jetbrains-mono": fontMono.style.fontFamily, "geist-mono": fontGeistMono.style.fontFamily, "ibm-plex-mono": fontIbmMono.style.fontFamily, "system-mono": "ui-monospace, Consolas, monospace" }\n' +
    '  const bodyFamily = sansFonts[settings.bodyFont]\n' +
    '  const headingFamily = sansFonts[settings.headingFont]\n' +
    '  const codeFamily = codeFonts[settings.codeFont]'
  )
  layout = layout.replace(
    'className={fontSans.variable + " " + fontMono.variable + " ng-official-docs"}',
    'className={fontClasses + " ng-official-docs"} style={Object.assign({ fontFamily: bodyFamily }, { "--ng-heading-font": headingFamily, "--ng-code-font": codeFamily })}'
  )
  plan.files[layoutFile] = layout
  const pageFile = plan.router.folder + (plan.basePath === "/" ? "/(nextguide)" : "/docs") + "/[[...slug]]/page." + ext
  let page = plan.files[pageFile]
  if (!page || !page.includes("export async function generateMetadata")) {
    throw new Error("NextGuide account pages are incompatible with the generated starter.")
  }
  page = page.replace('import { Suspense } from "react"', 'import { Suspense } from "react"\nimport { getStudioSettings } from "nextguide/account/cms"')
  page = page.replace('  let frontmatter\n  try {', '  const runtimeSite = getStudioSettings(process.cwd())\n  let frontmatter\n  try {')
    .replace('site.description ?? ""', 'runtimeSite.description ?? ""')
    .replace('"url" in site && typeof site.url === "string" && /^https?:\\/\\//.test(site.url)', 'runtimeSite.url && /^https?:\\/\\//.test(runtimeSite.url)')
    .replace('new URL(imagePath, site.url.replace', 'new URL(imagePath, runtimeSite.url.replace')
    .replace('branding.ogImage || imageUrl', 'runtimeSite.ogImage || imageUrl')
  plan.files[pageFile] = page
  // Social preview cards should use the account owner's latest site identity.
  const ogFile = plan.router.folder + '/og/[...slug]/route.' + (plan.typed ? 'ts' : 'js')
  let ogSource = plan.files[ogFile]
  if (ogSource) {
    ogSource = ogSource.replace('import { ImageResponse } from "next/og"',
      'import { ImageResponse } from "next/og"\nimport { getStudioSettings } from "nextguide/account/cms"')
    ogSource = ogSource.replace('  const frontmatter = await docs.getFrontmatter({ slug })',
      '  const settings = getStudioSettings(process.cwd())\n  const frontmatter = await docs.getFrontmatter({ slug })')
    ogSource = ogSource.replace('siteName: site.name,', 'siteName: settings.name,')
      .replace('frontmatter.description ?? site.description', 'frontmatter.description ?? settings.description')
      .replace('appearance: appearance.mode,', 'appearance: settings.theme,')
      .replace('accent: appearance.accent,', 'accent: settings.accent,')
    plan.files[ogFile] = ogSource
  }
  const styleFile = (plan.router.folder.startsWith("src/") ? "src/" : "") + "styles/nextguide.css"
  plan.files[styleFile] += "\n/* Account Mode: user-selected document typography. */\n.ng-official-docs :is(h1,h2,h3,h4,h5,h6) { font-family: var(--ng-heading-font, var(--font-sans)) !important; }\n.ng-official-docs :is(code,pre,kbd) { font-family: var(--ng-code-font, var(--font-mono)) !important; }\n"
  const privateFile = accountFile(directory)
  if (!options.dryRun && existsSync(privateFile)) {
    throw new Error("Account storage already exists. Refusing to overwrite an owner or a setup token.")
  }
  // Create the owner token before changing project files. If a project-file
  // conflict occurs, restore the storage preflight without touching existing data.
  const bootstrap = options.dryRun ? null : createBootstrap(directory)
  let result
  try { result = applyPlan(plan, Boolean(options.dryRun)) }
  catch (error) {
    if (bootstrap && existsSync(bootstrap.file)) unlinkSync(bootstrap.file)
    throw error
  }
  return { ...result, router: plan.router, mode: "account", projectDirectory: directory,
    basePath: plan.basePath, appearance: plan.appearance, bootstrapToken: bootstrap?.token ?? null,
    privateDirectory: bootstrap ? bootstrap.file : privateFile,
    dryRun: Boolean(options.dryRun) }
}
