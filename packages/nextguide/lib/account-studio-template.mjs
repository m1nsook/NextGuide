// Generated studio API: all editor actions are server-side and session-protected.
// The editor cannot access a public file write endpoint.
const STUDIO_API = `// Generated by NextGuide CLI. Edit freely; NextGuide never overwrites these files.
import { ACCOUNT_COOKIE, AccountError, verifySession, sameOrigin } from "nextguide/account/server"
import { listStudioPages, readStudioPage, saveStudioPage, deleteStudioPage, getStudioNavigation, setStudioNavigation, getStudioSettings, saveStudioSettings, listStudioMedia, uploadStudioMedia, deleteStudioMedia } from "nextguide/account/cms"
import { createAccountAddonManager } from "nextguide/extensions/site-manager"


function response(data__DATA_TYPE__, status = 200) {
  return Response.json(data, { status, headers: { "Cache-Control": "private, no-store", "X-Content-Type-Options": "nosniff" } })
}
function sessionCookie(request__REQUEST_TYPE__) {
  const cookie = (request.headers.get("cookie") || "").match(/(?:^|;\\s*)ng_account_session=([^;]+)/)
  try { return cookie ? decodeURIComponent(cookie[1]) : "" } catch { return "" }
}
async function body(request__REQUEST_TYPE__, limit = 3_000_000) {
  if (!(request.headers.get("content-type") || "").toLowerCase().startsWith("application/json"))
    throw new AccountError("JSON request required.", 415)
  const reader = request.body?.getReader()
  if (!reader) throw new AccountError("Missing request body.", 400)
  const chunks = []
  let total = 0
  while (true) {
    const next = await reader.read()
    if (next.done) break
    total += next.value.byteLength
    if (total > limit) { await reader.cancel(); throw new AccountError("Request is too large.", 413) }
    chunks.push(Buffer.from(next.value))
  }
  try { return JSON.parse(Buffer.concat(chunks).toString("utf8")) }
  catch { throw new AccountError("Malformed JSON.", 400) }
}
function errorResponse(error__ERROR_TYPE__) {
  if (error instanceof AccountError) return response({ error: error.message }, error.status)
  const allowed = new Map([
    ["INVALID_REQUEST",400], ["CONSENT_REQUIRED",403], ["INCOMPATIBLE",409],
    ["NOT_APPROVED",409], ["DOWNGRADE",409], ["NOT_INSTALLED",404], ["CONFLICT",409],
    ["CAPACITY",409], ["PERMISSION_DENIED",403], ["STALE_CATALOG",503], ["BUSY",503],
    ["MODE_DENIED",403], ["MISSING_ARTIFACT",409], ["CORRUPT_ARTIFACT",409],
    ["NO_REGISTRY",503], ["UNSAFE_STORAGE",503], ["DAMAGED_STATE",503],
  ])
  const code = error && typeof error === "object" && "code" in error ? String(error.code) : ""
  if (allowed.has(code)) {
    const safe = new Map([
      ["CONFLICT","Add-on state changed. Refresh and try again."],
      ["NOT_APPROVED","This release is not approved, is revoked or is incompatible."],
      ["STALE_CATALOG","The signed registry metadata needs to be refreshed."],
      ["INCOMPATIBLE","This add-on is incompatible with your installed NextGuide version."],
      ["CONSENT_REQUIRED","Confirm the requested installation change before continuing."],
    ])
    return response({ error: safe.get(code) || "Add-on operation denied (" + code + ")." }, allowed.get(code) || 503)
  }
  console.error("[nextguide/studio] Studio error", error instanceof Error ? error.name : "Unknown")
  return response({ error: "Studio service failed. Check server logs." }, 503)
}
function authorized(request__REQUEST_TYPE__) {
  return verifySession(process.cwd(), sessionCookie(request))
}
export async function GET(request__REQUEST_TYPE__, { params }__PARAM_TYPE__) {
  try {
    if (!authorized(request)) return response({ error: "Sign in to access the editor." }, 401)
    const action = (await params).action
    const url = new URL(request.url)
    if (action === "overview") return response({
      site: getStudioSettings(process.cwd()),
      pages: listStudioPages(process.cwd()),
      navigation: getStudioNavigation(process.cwd()),
      media: listStudioMedia(process.cwd()),
    })
    if (action === "addons") {
      return response(await createAccountAddonManager({ project: process.cwd() }).catalog())
    }
    if (action === "page") return response(readStudioPage(process.cwd(), url.searchParams.get("slug") ?? ""))
    if (action === "navigation") return response(getStudioNavigation(process.cwd(), url.searchParams.get("folder") ?? ""))
    if (action === "settings") return response(getStudioSettings(process.cwd()))
    if (action === "media") return response(listStudioMedia(process.cwd()))
    return response({ error: "Not found" }, 404)
  } catch (error) { return errorResponse(error) }
}
export async function POST(request__REQUEST_TYPE__, { params }__PARAM_TYPE__) {
  try {
    if (!authorized(request)) return response({ error: "Sign in to access the editor." }, 401)
    if (!sameOrigin(request)) return response({ error: "Invalid origin." }, 403)
    const action = (await params).action
    if (!["save-page","delete-page","save-settings","save-navigation","upload-media","delete-media","addon-install","addon-toggle","addon-rollback","addon-uninstall"].includes(action))
      return response({ error: "Not found" }, 404)
    const input = await body(request, action === "upload-media" ? 3_000_000 : 450_000)
    if (action.startsWith("addon-")) {
      const addons = createAccountAddonManager({ project: process.cwd() })
      if (action === "addon-install") return response(await addons.install(input))
      if (action === "addon-toggle") return response(await addons.toggle(input))
      if (action === "addon-rollback") return response(await addons.rollback(input))
      if (action === "addon-uninstall") return response(addons.uninstall(input))
      return response({ error: "Not found" }, 404)
    }
    if (action === "save-page") return response(saveStudioPage(process.cwd(), input))
    if (action === "delete-page") return response(deleteStudioPage(process.cwd(), input.slug, input.version))
    if (action === "save-settings") return response(saveStudioSettings(process.cwd(), input))
    if (action === "save-navigation") return response(setStudioNavigation(process.cwd(), input))
    if (action === "upload-media") return response(uploadStudioMedia(process.cwd(), input.mime, input.base64))
    return response(deleteStudioMedia(process.cwd(), input.name))
  } catch (error) { return errorResponse(error) }
}
`
export function fullStudioRouteSource(typed = true) {
  return STUDIO_API
    .replaceAll("__REQUEST_TYPE__", typed ? ": Request" : "")
    .replaceAll("__PARAM_TYPE__", typed ? ": { params: Promise<{ action: string }> }" : "")
    .replaceAll("__DATA_TYPE__", typed ? ": unknown" : "")
    .replaceAll("__ERROR_TYPE__", typed ? ": unknown" : "")
}
